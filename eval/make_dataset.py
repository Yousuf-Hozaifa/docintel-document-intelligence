"""Deterministic labeled synthetic dataset.  python eval/make_dataset.py --split dev|test
Writes eval/dataset/<split>/files/* and manifest.json (ground truth + expected validation rules per invoice).

Everything is generated by the same author as the extractor: results are an UPPER BOUND for real invoices.
dev = for debugging the system; test = different seed, larger, run before any fix and reported as the primary result."""
