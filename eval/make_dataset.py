PLAN = {  # category -> files in the test split (dev uses ~40%)
    "digital_pdf": 24, "scanned_pdf": 14, "png": 8, "jpg": 8, "tiff": 6, "xlsx": 12, "xls": 6, "csv": 8, "xlsx_register": 3,
    "degraded_blur": 6, "degraded_lowres": 6, "degraded_rotate": 6,
    "missing_fields": 12, "ambiguous_date": 4, "tampered_total": 6, "line_error": 4, "multi_invoice_pdf": 3,
    "xdoc_verified": 4, "xdoc_mismatch": 3, "duplicate_pdf": 3,
    "neg_corrupt_pdf": 3, "neg_truncated_png": 2, "neg_corrupt_xlsx": 2, "neg_empty": 2, "neg_encrypted": 2,
    "neg_unsupported": 2, "neg_binary_csv": 1, "neg_mismatch": 2, "neg_blank_image": 2,
}
FILE_TYPE = {"digital_pdf": "pdf-digital", "scanned_pdf": "pdf-scanned", "png": "png", "jpg": "jpg", "tiff": "tiff", "xlsx": "xlsx", "xls": "xls",
             "csv": "csv", "xlsx_register": "xlsx-register", "degraded_blur": "png-degraded", "degraded_lowres": "png-degraded",
             "degraded_rotate": "png-degraded", "missing_fields": "pdf-digital", "ambiguous_date": "pdf-digital", "tampered_total": "pdf-digital",
             "line_error": "pdf-digital", "multi_invoice_pdf": "pdf-digital", "xdoc_verified": "pdf+register", "xdoc_mismatch": "pdf+register",
             "duplicate_pdf": "pdf-digital"}
OMITS = [{"customer"}, {"tax"}, {"date"}, {"number"}, {"currency"}, {"customer", "tax"}, {"date", "currency"}, {"tax", "number"}]
REQ_FIELD = {"customer": "customer", "date": "invoice_date", "number": "invoice_number", "currency": "currency"}
NUMBER_FORMATS = ["INV-{n}", "{y}-{n:04d}", "SI/{n}/24"]
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]


class Maker:
    def __init__(self, seed: int, number_base: int):
        self.rng, self.n = random.Random(seed), number_base

    def spec(self, layout=None, **kw) -> S.Spec:
        r = self.rng; self.n += 1
        items = [(d, r.randint(1, 9), Decimal(r.randint(500, 499900)) / 100) for d in r.sample(S.ITEMS, r.randint(2, 6))]
        cur = r.choice(["USD", "EUR", "GBP"])
        style = r.choice(["code", "code", "code", "symbol"]) if cur in S.SYMBOLS else "code"
        y, m, d = 2024, r.randint(1, 12), r.randint(1, 28)
        sp = S.Spec(number=r.choice(NUMBER_FORMATS).format(n=self.n, y=y), date_iso=f"{y}-{m:02d}-{d:02d}", supplier=r.choice(S.SUPPLIERS),
                    customer=r.choice(S.CUSTOMERS), currency=cur, items=items, tax_rate=r.choice([Decimal("0.05"), Decimal("0.10"), Decimal("0.20")]),
                    layout=layout or r.choice("ABC"), currency_style=style, thousands=r.random() < 0.5)
        styles = ["iso", "dmy_long", "mdy_long", "dmy_mon"] + (["dmy_slash"] if d >= 13 else [])
        st = r.choice(styles)
        sp.date_text = {"iso": sp.date_iso, "dmy_long": f"{d} {MONTHS[m - 1]} {y}", "mdy_long": f"{MONTHS[m - 1]} {d}, {y}",
                        "dmy_mon": f"{d:02d}-{MONTHS[m - 1][:3]}-{y}", "dmy_slash": f"{d:02d}/{m:02d}/{y}"}[st]
        for k, v in kw.items(): setattr(sp, k, v)
        return sp


def entry(path: Path, category: str, specs=None, expect="success", error_code=None, rules=None, line_items=True, notes=""):
    invs = []
    for i, sp in enumerate(specs or []):
        t = sp.truth()
        invs.append({"fields": {k: t[k] for k in ("invoice_number", "invoice_date", "supplier", "customer", "subtotal", "tax", "total", "currency")},
                     "line_items": t["line_items"] if line_items else None, "expected_rules": (rules[i] if rules else [])})
    return {"file": path.name, "category": category, "file_type": FILE_TYPE.get(category, category), "expect": expect,
            "error_code": error_code, "invoices": invs, "notes": notes}


def build(split: str, seed: int, scale: float, number_base: int) -> list[dict]:
    out_dir = ROOT / "eval" / "dataset" / split
    if out_dir.exists(): shutil.rmtree(out_dir)
    files = out_dir / "files"; files.mkdir(parents=True)
    mk, rng = Maker(seed, number_base), random.Random(seed + 1)
    man: list[dict] = []
    count = lambda c: max(1, math.ceil(PLAN[c] * scale)) if scale < 1 else PLAN[c]
    for cat in PLAN:
        for i in range(count(cat)):
            nm = f"{cat}_{i:03d}"; lay = "ABC"[i % 3]
            def P(ext): return files / f"{nm}.{ext}"
            if cat == "digital_pdf":
                sp = mk.spec(lay); man.append(entry(S.write_pdf(sp, P("pdf")), cat, [sp]))
            elif cat == "scanned_pdf":
                sp = mk.spec(lay); man.append(entry(S.write_scanned_pdf([sp], P("pdf"), dpi=200), cat, [sp]))
            elif cat in ("png", "jpg"):
                sp = mk.spec(lay); man.append(entry(S.write_image(sp, P(cat), dpi=200), cat, [sp]))
            elif cat == "tiff":
                sps = [mk.spec(lay), mk.spec(lay)]; man.append(entry(S.write_tiff(sps, P("tiff"), dpi=200), cat, sps))
            elif cat == "xlsx":
                sps = [mk.spec(lay)] + ([mk.spec(lay)] if i % 4 == 3 else []); man.append(entry(S.write_xlsx(sps, P("xlsx")), cat, sps))
            elif cat == "xls":
                sps = [mk.spec(lay)] + ([mk.spec(lay)] if i % 3 == 2 else []); man.append(entry(S.write_xls(sps, P("xls")), cat, sps))
            elif cat == "csv":
                sp = mk.spec(lay); man.append(entry(S.write_csv(sp, P("csv"), delimiter=[",", ";", "\t"][i % 3]), cat, [sp]))
            elif cat == "xlsx_register":
                sps = [mk.spec() for _ in range(5)]; man.append(entry(S.write_register_xlsx(sps, P("xlsx"), header=i % 2), cat, sps, line_items=False))
            elif cat.startswith("degraded_"):
                mode = cat.split("_")[1]; sp = mk.spec(lay); man.append(entry(S.write_image(sp, P("png"), degrade=mode), cat, [sp]))
            elif cat == "missing_fields":
                om = OMITS[i % len(OMITS)]; sp = mk.spec(lay, omit=frozenset(om), currency_style="none" if "currency" in om else None or "code")
                if "currency" in om: sp.currency_style = "none"
                rules = [[["VAL-REQ-001", REQ_FIELD[o]] for o in om if o in REQ_FIELD]]
                man.append(entry(S.write_pdf(sp, P("pdf")), cat, [sp], rules=rules, notes=f"omit={sorted(om)}"))
            elif cat == "ambiguous_date":
                sp = mk.spec(lay); m, d = rng.randint(1, 12), rng.choice([d for d in range(1, 13)])
                while m == d: d = rng.randint(1, 12)
                sp.date_iso, sp.date_text, sp.date_ambiguous = f"2024-{m:02d}-{d:02d}", f"{d:02d}/{m:02d}/2024", True
                man.append(entry(S.write_pdf(sp, P("pdf")), cat, [sp], rules=[[["VAL-DATE-002", "invoice_date"]]]))
            elif cat == "tampered_total":
                sp = mk.spec(lay); sp.total_override = sp.subtotal + sp.tax + Decimal(rng.choice([-1, 1]) * rng.randint(5, 500))
                man.append(entry(S.write_pdf(sp, P("pdf")), cat, [sp], rules=[[["VAL-SUB-001", None]]]))
            elif cat == "line_error":
                sp = mk.spec(lay); sp.line_override = {0: sp.q(Decimal(sp.items[0][1]) * sp.items[0][2]) + Decimal(rng.randint(5, 200))}
                man.append(entry(S.write_pdf(sp, P("pdf")), cat, [sp], rules=[[["VAL-LINE-001", None]]]))
            elif cat == "multi_invoice_pdf":
                sps = [mk.spec(lay) for _ in range(3)]; man.append(entry(S.write_digital_pdf(sps, P("pdf")), cat, sps))
            elif cat in ("xdoc_verified", "xdoc_mismatch"):
                sp, others = mk.spec(lay), [mk.spec(), mk.spec()]
                mism = cat == "xdoc_mismatch"
                delta = Decimal(rng.randint(10, 400)) if mism else Decimal(0)
                reg_spec = S.Spec(**{**sp.__dict__})  # register row shows the (possibly altered) total
                man.append(entry(S.write_pdf(sp, files / f"{nm}_doc.pdf"), cat, [sp], rules=[[["VAL-XDOC-001" if mism else "VAL-XDOC-002", None]]]))
                reg = S.write_register_xlsx([sp] + others, files / f"{nm}_register.xlsx", totals={sp.number: sp.total + delta} if mism else None, header=i % 2)
                reg_sp = S.Spec(**{**sp.__dict__, "total_override": sp.total + delta})
                rules = [[["VAL-XDOC-001", None], ["VAL-SUB-001", None]] if mism else [["VAL-XDOC-002", None]], [], []]
                man.append(entry(reg, cat, [reg_sp] + others, rules=rules, line_items=False))
            elif cat == "duplicate_pdf":
                sp = mk.spec("A"); sp2 = S.Spec(**{**sp.__dict__, "layout": "C"})
                man.append(entry(S.write_pdf(sp, files / f"{nm}_a.pdf"), cat, [sp], rules=[[["VAL-DUP-001", None]]]))
                man.append(entry(S.write_pdf(sp2, files / f"{nm}_b.pdf"), cat, [sp2], rules=[[["VAL-DUP-001", None]]]))
            # ------------------------------------------------ negatives
            elif cat == "neg_corrupt_pdf":
                g = S.write_pdf(mk.spec(), P("tmp")).read_bytes(); P("tmp").unlink(); P("pdf").write_bytes(b"%PDF-1.4\n" + g[20:120 + 40 * i])
                man.append(entry(P("pdf"), cat, expect="failed", error_code="corrupt_file"))
            elif cat == "neg_truncated_png":
                S.write_image(mk.spec(), P("tmp")) if False else None
                g = S.write_image(mk.spec(), P("png"), dpi=100).read_bytes(); P("png").write_bytes(g[: len(g) // (2 + i)])
                man.append(entry(P("png"), cat, expect="failed", error_code="corrupt_file"))
            elif cat == "neg_corrupt_xlsx":
                P("xlsx").write_bytes(b"PK\x03\x04" + bytes(rng.randrange(256) for _ in range(300))); man.append(entry(P("xlsx"), cat, expect="failed", error_code="corrupt_file"))
            elif cat == "neg_empty":
                P("pdf" if i % 2 == 0 else "csv").write_bytes(b""); man.append(entry(next(files.glob(f"{nm}.*")), cat, expect="rejected"))
            elif cat == "neg_encrypted":
                g = S.write_pdf(mk.spec(), files / f"{nm}_plain.pdf"); d = pymupdf.open(g)
                d.save(P("pdf"), encryption=pymupdf.PDF_ENCRYPT_AES_256, user_pw="secret", owner_pw="secret"); d.close(); g.unlink()
                man.append(entry(P("pdf"), cat, expect="failed", error_code="encrypted_file"))
            elif cat == "neg_unsupported":
                ext = ["exe", "docx"][i % 2]; P(ext).write_bytes(b"MZ\x90\x00" + b"\0" * 64); man.append(entry(P(ext), cat, expect="rejected"))
            elif cat == "neg_binary_csv":
                P("csv").write_bytes(bytes(rng.randrange(256) for _ in range(2000))); man.append(entry(P("csv"), cat, expect="failed", error_code="corrupt_file"))
            elif cat == "neg_mismatch":
                P("pdf").write_text("This is plain text pretending to be a PDF invoice.\nTotal: 5.00"); man.append(entry(P("pdf"), cat, expect="rejected"))
            elif cat == "neg_blank_image":
                Image.new("RGB", (1200, 1600), "white").save(P("png")); man.append(entry(P("png"), cat, expect="failed", error_code="no_extractable_content"))
    (out_dir / "manifest.json").write_text(json.dumps({"split": split, "seed": seed, "files": man}, indent=1))
    return man


