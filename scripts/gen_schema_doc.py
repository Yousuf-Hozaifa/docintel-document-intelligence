"""Generate docs/DATABASE.md (ERD + tables + indexes) from the REAL SQLite schema created by app.db.init_db()."""
import os, sqlite3, sys, tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
tmp = tempfile.mkdtemp(); os.environ["DOCINTEL_DATA_DIR"] = tmp
from app.db import init_db
init_db()
c = sqlite3.connect(Path(tmp) / "docintel.sqlite3"); c.row_factory = sqlite3.Row

PURPOSE = {
    "documents": "One row per uploaded file: name, SHA-256 (duplicate-upload protection), detected type, status, page counters, error code/message, review flag.",
    "jobs": "Background-processing queue and history: status, attempts/max_attempts, `run_after` (retry backoff), progress counters. A document can have several jobs (reprocessing).",
    "pages": "Extracted text per page/sheet with the method used (text layer, OCR, sheet, csv) and OCR mean confidence. Failed pages are kept with their error.",
    "invoices": "One row per invoice found in a document (a PDF or workbook can hold many). `fields_json` keeps the full extraction (value, confidence, evidence, OCR word confidence); the plain columns are the current values used for search/filters. `num_key` = normalised invoice number for cross-document matching.",
    "line_items": "Line items of an invoice (values kept as decimal strings); `evidence` is the source line; `ocr_conf` the weakest OCR word (cleared when a human edits the row).",
    "validation_issues": "Output of the deterministic rule engine, one row per finding with a stable `rule_id`; `resolved` marks human review.",
    "corrections": "Audit trail of manual edits: field, old value, new value, note, timestamp.",
    "events": "Processing history per document (uploaded, read_started, page_failed, completed, retry_scheduled, corrected, ...).",
    "chunks": "Optional semantic index: text chunks with an embedding BLOB (float32) and the model name that produced it.",
}
tables = [r["name"] for r in c.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE 'page_fts_%' ORDER BY rowid")]
L = ["# Database schema\n", "_Generated by `scripts/gen_schema_doc.py` from the real schema (`backend/app/db.py`). SQLite in WAL mode; one short transaction per unit of work._\n",
     "## Entity-relationship diagram\n", "```mermaid", "erDiagram"]
rel = []
for t in tables:
    if t == "page_fts":
        continue
    cols = c.execute(f"PRAGMA table_info({t})").fetchall()
    fks = {f["from"]: f for f in c.execute(f"PRAGMA foreign_key_list({t})")}
    L.append(f"  {t} {{")
    for col in cols:
        typ = (col["type"] or "TEXT").split("(")[0].replace(" ", "_") or "TEXT"
        key = " PK" if col["pk"] else (" FK" if col["name"] in fks else "")
        L.append(f"    {typ} {col['name']}{key}")
    L.append("  }")
    for f in fks.values():
        rel.append(f'  {f["table"]} ||--o{{ {t} : "has"')
L += rel + ["```\n"]
L.append("`page_fts` is an FTS5 virtual table (`text`, plus unindexed `document_id`, `page_no`; Porter stemming) that powers keyword search. SQLite cannot cascade deletes into it, so the API removes its rows explicitly.\n")
L.append("## Tables\n")
for t in tables:
    if t == "page_fts":
        continue
    cols = c.execute(f"PRAGMA table_info({t})").fetchall()
    L.append(f"### `{t}`\n\n{PURPOSE.get(t, '')}\n")
    L.append("| column | type | notes |\n|---|---|---|")
    fks = {f["from"]: f for f in c.execute(f"PRAGMA foreign_key_list({t})")}
    for col in cols:
        note = ", ".join(x for x in ["primary key" if col["pk"] else "", f"→ {fks[col['name']]['table']}.{fks[col['name']]['to']} (ON DELETE {fks[col['name']]['on_delete']})" if col["name"] in fks else "", "NOT NULL" if col["notnull"] and not col["pk"] else "", f"default {col['dflt_value']}" if col["dflt_value"] is not None else ""] if x)
        L.append(f"| {col['name']} | {col['type'] or ''} | {note} |")
    idx = [r["name"] for r in c.execute(f"PRAGMA index_list({t})") if not r["name"].startswith("sqlite_autoindex")]
    if idx:
        L.append("\nIndexes: " + ", ".join(f"`{i}` ({', '.join(x['name'] for x in c.execute(f'PRAGMA index_info({i})'))})" for i in idx))
    L.append("")
L += ["## Design notes\n",
      "- **Why SQLite (not PostgreSQL/pgvector) for now:** one cohesive CPU-first deployment, zero services to run on an 8 GB Windows machine. Measured limits and the point where a move is justified are in `docs/SEMANTIC.md` (brute-force vectors up to ~250k chunks) and `docs/benchmarks/`.",
      "- **Money is stored as decimal strings**, never floats; arithmetic uses Python `Decimal` with per-currency precision.",
      "- **Denormalised columns on `invoices`** (number, date, supplier, customer, totals, currency) mirror `fields_json` so search/filters need no JSON parsing; they are updated together by the correction code.",
      "- **Concurrency:** WAL journal, `BEGIN IMMEDIATE` transactions, jobs claimed atomically (`UPDATE … WHERE status='queued'` inside one transaction), so two workers never run the same job.",
      "- **Migrations:** `init_db()` creates missing tables and adds later columns (`invoices.num_key`, `line_items.ocr_conf`) in place; there is no separate migration tool.",
      "- **Deletion:** `DELETE /api/documents/{id}` removes the file, FTS rows and (via cascade) everything derived from it.", ""]
(ROOT / "docs" / "DATABASE.md").write_text("\n".join(L))
print("wrote docs/DATABASE.md with", len([t for t in tables if t != 'page_fts']), "tables")
